            CALL MATRIX_1(P ,NHEL(1,IHEL),T)
          ENDIF
        ENDDO
      ENDIF
      DO I=1,NSQAMPSO
        ANS(I)=ANS(I)/DBLE(IDEN)
        ANS(0)=ANS(0)+ANS(I)
      ENDDO
      END


