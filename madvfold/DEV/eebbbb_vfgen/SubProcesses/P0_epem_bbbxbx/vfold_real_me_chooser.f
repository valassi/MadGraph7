      INTEGER FUNCTION NFKS_REAL_LIBRARY(NFKSPROCESS)
      IMPLICIT NONE
      INTEGER NFKSPROCESS
      IF (NFKSPROCESS.EQ.1) THEN
        NFKS_REAL_LIBRARY = 1
      ELSEIF (NFKSPROCESS.EQ.2) THEN
        NFKS_REAL_LIBRARY = 1
      ELSE
        WRITE(*,*) 'ERROR: invalid n in NFKS_REAL_LIBRARY :',
     $    NFKSPROCESS
        STOP
      ENDIF
      RETURN
      END

